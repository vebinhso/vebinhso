/** Hiệu ứng camera cho từng cảnh để ảnh tĩnh "sống" như video */
export type Motion = "kenburns" | "push" | "shake" | "freeze";

export type FilmNode = {
  id: string;
  image: string;
  video?: string;
  speaker: Speaker;
  action?: string;
  text: string;
  motion?: Motion;
  /** phủ màu: nguy hiểm (lạnh) hay an toàn (ấm) */
  mood?: "danger" | "safe" | "neutral";
  /** Hiện lớp phủ thông báo email giả mạo */
  emailOverlay?: boolean;
  /** Lớp phủ soi kỹ dấu hiệu lừa đảo (địa chỉ email lạ, link .net) */
  inspectOverlay?: boolean;
  /** Hiện lớp phủ nội dung email lừa đảo (dựng bằng CSS) */
  mailOverlay?: boolean;
  /** Lớp phủ biểu mẫu trang web giả đòi thông tin + mật khẩu game */
  formOverlay?: boolean;
  /** Lớp phủ điện thoại hiển thị form đã điền đầy đủ thông tin */
  phoneFormOverlay?: boolean;
  /** Lớp phủ bài đăng cảnh báo tiếng Việt hiển thị ngay trên màn hình điện thoại */
  warnPostOverlay?: boolean;
  phoneConfirm?: boolean;
  /** Nhãn tiếng Việt hiển thị đè lên nút vàng trong khung hình (theo % khung 16:9) */
  confirmBtn?: { x: number; y: number; w: number; rot?: number };
  /** Vị trí khung điện thoại trên khung hình (theo % của khung 16:9), khớp với điện thoại nhân vật đang cầm */
  phoneAnchor?: { x: number; y: number; h: number; rot?: number };
  /** Dựng lại màn hình form nhận thưởng bằng CSS cho rõ nét (đè lên vùng màn hình trong khung 16:9) */
  formScreen?: { x: number; y: number; w: number; h: number; rot?: number };
  /** Vá tối một vùng màn hình điện thoại để che biểu tượng có sẵn trong video */
  screenPatch?: { x: number; y: number; w: number; h: number; rot?: number };
  /** ảnh riêng khi hiện lựa chọn */
  choiceImage?: string;
  next?: string;
  choices?: Choice[];
  ending?: {
    kind: "safe" | "loss";
    code: string;
    title: string;
    lesson: string;
  };
};

